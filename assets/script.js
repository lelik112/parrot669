const htmlNodes = document.querySelectorAll("[data-i18n-html]");
const textNodes = document.querySelectorAll("[data-i18n]");
const langButtons = document.querySelectorAll("[data-lang]");

function setLanguage(lang){
  const t = translations[lang] || translations.en;
  document.documentElement.lang = lang;
  textNodes.forEach(node => {
    const key = node.dataset.i18n;
    if(t[key] !== undefined) node.textContent = t[key];
  });
  htmlNodes.forEach(node => {
    const key = node.dataset.i18nHtml;
    if(t[key] !== undefined) node.innerHTML = t[key];
  });
  langButtons.forEach(btn => btn.classList.toggle("active", btn.dataset.lang === lang));
  localStorage.setItem("parrot669-language", lang);
}

langButtons.forEach(btn => btn.addEventListener("click", () => setLanguage(btn.dataset.lang)));

const saved = localStorage.getItem("parrot669-language");
const browser = (navigator.language || "en").slice(0,2);
setLanguage(saved || (translations[browser] ? browser : "en"));

document.getElementById("year").textContent = new Date().getFullYear();

const form = document.getElementById("lead-form");
const status = document.getElementById("form-status");

form.addEventListener("submit", async (event) => {
  event.preventDefault();
  const data = Object.fromEntries(new FormData(form).entries());
  const text = [
    "PARROT 669 request",
    "",
    `Name: ${data.name}`,
    `Contact: ${data.contact}`,
    `Service: ${data.service}`,
    "",
    data.message
  ].join("\n");

  try {
    await navigator.clipboard.writeText(text);
    status.textContent = "Request copied to clipboard. Connect the form to email/Formspree before launch.";
  } catch {
    status.textContent = text;
  }
});
